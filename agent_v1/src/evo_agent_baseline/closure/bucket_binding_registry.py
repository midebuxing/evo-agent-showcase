def _schema_violations() -> List[str]:
    """导入期模式 / 重复键 / 政策 / **粒度声明**校验。

    🔴 **零碰撞必须是不变量，不是一次性审计**（两家族都点名要求）：
    336 个 `(卡, artifact_key)` 今天零碰撞，但改卡就可能引入碰撞。
    没有这道闸，键会**静默**从「唯一」变成「一对多」，无人报警。

    🔴 **同卡同质闸在这里是跨表的**（DEBT-085 件二·声明期，决策门 Q1）：
    本表 20 张卡与 A 表候选卡重合 6 张（2026-08-04 实测：A 表 ∩ 桶表共 48 张卡），
    故「一卡内全部行同粒度」必须跨两张表看。**方向只能是桶表看 A 表**——
    桶表模块级已导入 A 表（`_c55_bucket_vc_views`），反向加会成环
    （A 表的 `_validate_against_pack` 在模块级执行，导入桶表会撞上
    尚未初始化的 `ACTIVE_ROWS`）。⇒ 跨表冲突时**桶表**整表 fail-closed，
    A 表仍活——这条残余不对称是已知尾巴，见
    `团队文档/我的笔记/实施记录_件二声明期_20260804.md`，第二步冻结时收口。
    """
    bad: List[str] = []
    seen = set()
    for r in BUCKET_BINDING_CONTRACTS:
        key = (r.get("rule_card_id"), r.get("artifact_key"))
        if not all(key):
            bad.append(f"row{r.get('row')}: 键不完整 {key}")
        if key in seen:
            bad.append(f"row{r.get('row')}: 重复键 {key}")
        seen.add(key)
        if r.get("policy") != "diagnostic_only":
            bad.append(f"row{r.get('row')}: 非法 policy {r.get('policy')!r}")
        if r.get("verdict_permission") != "none":
            bad.append(f"row{r.get('row')}: 诊断型必须 verdict_permission=none")
        if len(str(r.get("card_content_sha256") or "")) != 64:
            bad.append(f"row{r.get('row')}: 卡指纹形状不对")
        # 🔴 槽必须全属产物域（W0-09 登记表）——这是本表**统一声明出口**的结构性依据：
        # 产物态事实经分类器必落产物态码，声明与分流结构上一致；
        # 若混进非产物槽，丁⑤会在运行时 fail-closed——在这里拦，早一步。
        if str(r.get("slot_id") or "") not in _W0_09:
            bad.append(f"row{r.get('row')}: 槽 {r.get('slot_id')!r} 不在产物槽登记表")
    # ---- DEBT-085 件二·声明期：粒度声明枚举 ＋ 同卡同质（跨两表，见 docstring）----
    # 校验器定义只在 A 表一份，本表导入复用——两套实现＝「同一假设散在多层」。
    from evo_agent_baseline.closure.binding_contract_registry import (
        granularity_declaration_violations, BINDING_CONTRACTS as _A_ROWS,
    )
    bad.extend(granularity_declaration_violations(
        BUCKET_BINDING_CONTRACTS, "桶表"))
    # 跨表：把两表的**已声明**行并起来再判同卡同质。A 表侧的枚举违例由 A 表
    # 自己的闸报，这里只关心「同卡跨表冲突」，故只取合法声明行喂进来。
    # 行号在两表各自独立（都从小数字起），**必须带表名重贴标**，否则冲突
    # 报文里的 "row105" 指哪张表读不出来。
    _cross = [
        {**r, "row": f"{tbl}row{r.get('row')}"}
        for tbl, rows in (("A表", _A_ROWS), ("桶表", BUCKET_BINDING_CONTRACTS))
        for r in rows
        if r.get("granularity_declaration") in ("building", "fragment")
    ]
    bad.extend(v for v in granularity_declaration_violations(_cross, "跨表")
               if "同卡粒度声明冲突" in v)
    return bad


def _validate_against_pack():
    """卡指纹逐行核对；**任何模式违例 ⇒ 全表失效**（与 A 表同构的 fail-closed）。"""
    from evo_agent_baseline.closure.applicability_v3 import rulecard_content_digests

    schema_bad = _schema_violations()
    if schema_bad:
        return [], list(BUCKET_BINDING_CONTRACTS), f"schema:{schema_bad[:3]}"
    try:
        _pack, shas = rulecard_content_digests(_REPO_ROOT)
    except Exception as exc:  # noqa: BLE001 —— fail-closed 全表失效
        return [], list(BUCKET_BINDING_CONTRACTS), f"card_pack_unreadable:{exc}"
    if not shas:
        return [], list(BUCKET_BINDING_CONTRACTS), "card_pack_unreadable"
    active, stale = [], []
    for r in BUCKET_BINDING_CONTRACTS:
        (active if shas.get(r["rule_card_id"]) == r["card_content_sha256"]
         else stale).append(r)
    return active, stale, None


